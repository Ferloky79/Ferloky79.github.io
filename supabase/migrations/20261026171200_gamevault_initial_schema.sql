create function private.catalogo() returns jsonb language sql stable security definer set search_path='' as $$
 select coalesce(jsonb_agg(jsonb_build_object(
 'id',p.id_producto,'titulo',v.titulo,'descripcion',v.descripcion,'edicion',p.edicion,
 'plataforma',c.codigo,'region',p.region,'precioCentavos',p.precio_centavos,
 'precioAnteriorCentavos',p.precio_anterior_centavos,'valoracion',coalesce(v.valoracion_referencia,0),
 'imagen',p.imagen_url,'disponible',exists(select 1 from public.clave_digital k where k.id_producto=p.id_producto and k.estado='DISPONIBLE')
 ) order by p.id_producto),'[]'::jsonb)
 from public.producto p join public.videojuego v using(id_videojuego) join public.categoria c using(id_categoria)
 where p.publicado and c.activo;
$$;
create function public.obtener_catalogo() returns jsonb language sql stable security invoker set search_path='' as $$ select private.catalogo(); $$;

create function private.guardar_carrito(p_ids bigint[]) returns uuid language plpgsql security definer set search_path='' as $$
 declare v_id uuid; begin
 if auth.uid() is null or not private.es_cliente_activo() then raise exception 'Inicia sesión para guardar tu carrito'; end if;
 if p_ids is null or cardinality(p_ids)>100 or array_position(p_ids,null) is not null then raise exception 'Carrito inválido'; end if;
 perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text,0));
 insert into public.carrito(id_usuario) values(auth.uid()) on conflict(id_usuario) where estado='ACTIVO' do update set actualizado_en=now() returning id_carrito into v_id;
 if exists(select 1 from unnest(p_ids) x where not exists(select 1 from public.producto p join public.categoria c using(id_categoria) where p.id_producto=x and p.publicado and c.activo)) then raise exception 'Un producto ya no está publicado'; end if;
 delete from public.detalle_carrito where id_carrito=v_id;
 insert into public.detalle_carrito(id_carrito,id_producto) select v_id,x from (select distinct unnest(p_ids) x) d;
 return v_id;
 end;
$$;
create function public.guardar_carrito(p_ids bigint[]) returns uuid language sql security invoker set search_path='' as $$ select private.guardar_carrito(p_ids); $$;

create function private.leer_pedido(p_id uuid,p_comprobante text default null) returns jsonb language plpgsql stable security definer set search_path='' as $$
 declare p public.pedido; result jsonb; begin
 select * into p from public.pedido where id_pedido=p_id;
 if not found or not ((p.id_usuario=auth.uid() and private.es_cliente_activo()) or
 (p.id_usuario is null and length(p_comprobante)>=64 and p.comprobante_hash=encode(sha256(convert_to(p_comprobante,'UTF8')),'hex'))) then
 raise exception 'Pedido no disponible' using errcode='42501'; end if;
 select jsonb_build_object('id',p.id_pedido,'numero',p.numero,'email',p.correo_entrega,'total',p.total_centavos,'fecha',p.creado_en,'estado',p.estado,
 'metodo',(select m.nombre from public.pago pa join public.metodo_pago m using(id_metodo_pago) where pa.id_pedido=p.id_pedido and pa.estado='APROBADO'),
 'juegos',coalesce((select jsonb_agg(jsonb_build_object('id',d.id_producto,'titulo',d.titulo_compra,'edicion',d.edicion_compra,
 'plataforma',c.codigo,'region',d.region_compra,'precioCentavos',d.precio_unitario_centavos,'precioAnteriorCentavos',d.precio_anterior_centavos,
 'imagen',pr.imagen_url,'codigo',k.codigo) order by d.id_detalle_pedido)
 from public.detalle_pedido d join public.producto pr using(id_producto) join public.categoria c using(id_categoria)
 join public.clave_digital k using(id_detalle_pedido) where d.id_pedido=p.id_pedido),'[]'::jsonb)) into result;
 return result;
 end;
$$;
create function public.obtener_pedido(p_id uuid,p_comprobante text default null) returns jsonb language sql stable security invoker set search_path='' as $$ select private.leer_pedido(p_id,p_comprobante); $$;

create function private.comprar_demo(p_id uuid,p_ids bigint[],p_correo text,p_metodo text,p_total integer,p_comprobante text) returns jsonb language plpgsql security definer set search_path='' as $$
 declare v_total integer; v_metodo smallint; v_carrito uuid; v_producto record; v_clave bigint; v_linea bigint; v_usuario uuid:=auth.uid(); begin
 if p_id is null or p_ids is null or cardinality(p_ids) not between 1 and 100 or array_position(p_ids,null) is not null or cardinality(p_ids)<>(select count(distinct x) from unnest(p_ids) x) then raise exception 'Selección inválida'; end if;
 if p_comprobante is null or length(p_comprobante) not between 64 and 256 then raise exception 'Comprobante inválido'; end if;
 if v_usuario is not null and not private.es_cliente_activo() then raise exception 'Cuenta inactiva'; end if;
 -- Serializa reintentos; la misma solicitud nunca consume otras claves.
 perform pg_advisory_xact_lock(hashtextextended(p_id::text,0));
 if exists(select 1 from public.pedido where id_pedido=p_id) then return private.leer_pedido(p_id,p_comprobante); end if;
 if p_correo is null or length(p_correo)>254 or p_correo !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then raise exception 'Correo inválido'; end if;
 -- Límite educativo por correo para evitar agotar inventario accidentalmente.
 perform pg_advisory_xact_lock(hashtextextended(lower(p_correo),1));
 if (select count(*) from public.pedido where correo_entrega=lower(trim(p_correo)) and creado_en>now()-interval '1 hour')>=10 then raise exception 'Límite de compras demo alcanzado; intenta en una hora'; end if;
 select id_metodo_pago into v_metodo from public.metodo_pago where codigo=p_metodo and activo;
 if v_metodo is null then raise exception 'Método no disponible'; end if;
 -- Orden estable de bloqueos: dos compras concurrentes no obtienen la misma clave.
 perform p.id_producto from public.producto p where p.id_producto=any(p_ids) order by p.id_producto for update;
 if (select count(*) from public.producto p join public.categoria c using(id_categoria) where p.id_producto=any(p_ids) and p.publicado and c.activo)<>cardinality(p_ids) then raise exception 'El catálogo cambió; recarga y revisa tu carrito'; end if;
 select sum(precio_centavos) into v_total from public.producto where id_producto=any(p_ids);
 if p_total is distinct from v_total then raise exception 'El precio cambió; recarga y confirma el nuevo total'; end if;
 if v_usuario is not null then v_carrito:=private.guardar_carrito(p_ids); end if;
 insert into public.pedido(id_pedido,id_usuario,id_carrito,correo_entrega,total_centavos,comprobante_hash)
 values(p_id,v_usuario,v_carrito,lower(trim(p_correo)),v_total,encode(sha256(convert_to(p_comprobante,'UTF8')),'hex'));
 for v_producto in select p.*,v.titulo,c.nombre as plataforma_compra from public.producto p join public.videojuego v using(id_videojuego) join public.categoria c using(id_categoria) where p.id_producto=any(p_ids) order by p.id_producto loop
 select id_clave into v_clave from public.clave_digital where id_producto=v_producto.id_producto and estado='DISPONIBLE' order by id_clave limit 1 for update;
 if v_clave is null then raise exception 'Un producto se agotó; recarga el catálogo'; end if;
 insert into public.detalle_pedido(id_pedido,id_producto,titulo_compra,edicion_compra,plataforma_compra,region_compra,precio_unitario_centavos,precio_anterior_centavos)
 values(p_id,v_producto.id_producto,v_producto.titulo,v_producto.edicion,v_producto.plataforma_compra,v_producto.region,v_producto.precio_centavos,v_producto.precio_anterior_centavos) returning id_detalle_pedido into v_linea;
 update public.clave_digital set estado='ENTREGADA',id_detalle_pedido=v_linea,entregada_en=now() where id_clave=v_clave;
 end loop;
 insert into public.pago(id_pedido,id_metodo_pago,importe_centavos,estado,referencia,confirmado_en) values(p_id,v_metodo,v_total,'APROBADO','DEMO-'||p_id,now());
 update public.pedido set estado='ENTREGADO' where id_pedido=p_id;
 if v_carrito is not null then update public.carrito set estado='COMPLETADO',actualizado_en=now() where id_carrito=v_carrito; end if;
 return private.leer_pedido(p_id,p_comprobante);
 end;
$$;
create function public.comprar_demo(p_id uuid,p_ids bigint[],p_correo text,p_metodo text,p_total integer,p_comprobante text) returns jsonb language sql security invoker set search_path='' as $$ select private.comprar_demo(p_id,p_ids,p_correo,p_metodo,p_total,p_comprobante); $$;

-- Invariantes diferidas: también protegen las ediciones desde SQL/Studio.
create function private.validar_pedido() returns trigger language plpgsql set search_path='' as $$
 declare v_id uuid; p public.pedido; begin
 if TG_TABLE_NAME='pedido' then v_id:=coalesce(new.id_pedido,old.id_pedido); else v_id:=coalesce(new.id_pedido,old.id_pedido); end if;
 select * into p from public.pedido where id_pedido=v_id;
 if not found then return null; end if;
 if p.total_centavos<>coalesce((select sum(precio_unitario_centavos) from public.detalle_pedido where id_pedido=v_id),0) then raise exception 'Total inconsistente'; end if;
 if p.estado in ('PAGADO','ENTREGADO') and (not exists(select 1 from public.detalle_pedido where id_pedido=v_id) or not exists(select 1 from public.pago where id_pedido=v_id and estado='APROBADO' and importe_centavos=p.total_centavos)) then raise exception 'Pedido sin líneas o pago aprobado'; end if;
 if p.estado='ENTREGADO' and exists(select 1 from public.detalle_pedido d where d.id_pedido=v_id and not exists(select 1 from public.clave_digital k where k.id_detalle_pedido=d.id_detalle_pedido and k.estado='ENTREGADA')) then raise exception 'Entrega incompleta'; end if;
 return null;
 end;
$$;
