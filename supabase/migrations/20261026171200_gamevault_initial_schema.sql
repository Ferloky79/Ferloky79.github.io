create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to anon, authenticated;

create table public.rol (
 id_rol smallint generated by default as identity primary key,
 nombre varchar(20) not null unique check (nombre in ('ADMIN','CLIENTE')),
 descripcion varchar(150)
);
create table public.usuario (
 id_usuario uuid primary key references auth.users(id) on delete restrict,
 id_rol smallint not null references public.rol,
 nombre varchar(100) not null check (length(trim(nombre)) between 2 and 100),
 activo boolean not null default true, creado_en timestamptz not null default now()
);
create unique index un_administrador on public.usuario(id_rol) where id_rol = 1;
create table public.categoria (
 id_categoria smallint generated by default as identity primary key,
 codigo varchar(10) not null unique check (codigo in ('ps5','xbox','switch')),
 nombre varchar(30) not null unique, descripcion varchar(200), activo boolean not null default true
);
create table public.videojuego (
 id_videojuego bigint generated by default as identity primary key,
 titulo varchar(150) not null check(length(trim(titulo))>0), descripcion text not null,
 valoracion_referencia numeric(2,1) check(valoracion_referencia between 0 and 5)
);
create table public.producto (
 id_producto bigint generated by default as identity primary key,
 id_videojuego bigint not null references public.videojuego,
 id_categoria smallint not null references public.categoria,
 edicion varchar(80) not null, region varchar(40) not null,
 precio_centavos integer not null check(precio_centavos>=0),
 precio_anterior_centavos integer check(precio_anterior_centavos>precio_centavos),
 imagen_url text not null check(imagen_url ~ '^(assets/|https://)'),
 publicado boolean not null default false, creado_en timestamptz not null default now(),
 unique(id_videojuego,id_categoria,edicion,region)
);
create table public.carrito (
 id_carrito uuid primary key default gen_random_uuid(),
 id_usuario uuid not null references public.usuario,
 estado varchar(15) not null default 'ACTIVO' check(estado in ('ACTIVO','COMPLETADO','ABANDONADO')),
 creado_en timestamptz not null default now(), actualizado_en timestamptz not null default now()
);
create unique index un_carrito_activo on public.carrito(id_usuario) where estado='ACTIVO';
create table public.detalle_carrito (
 id_carrito uuid not null references public.carrito on delete cascade,
 id_producto bigint not null references public.producto,
 agregado_en timestamptz not null default now(), primary key(id_carrito,id_producto)
);
create table public.pedido (
 id_pedido uuid primary key default gen_random_uuid(),
 numero varchar(30) not null unique default ('GV-' || replace(gen_random_uuid()::text,'-','')::varchar(26)),
 id_usuario uuid references public.usuario, id_carrito uuid unique references public.carrito,
 correo_entrega varchar(254) not null check(correo_entrega ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
 estado varchar(20) not null default 'PENDIENTE_PAGO' check(estado in ('PENDIENTE_PAGO','PAGADO','ENTREGADO','CANCELADO')),
 moneda char(3) not null default 'USD' check(moneda='USD'),
 total_centavos integer not null check(total_centavos>=0), creado_en timestamptz not null default now(),
 comprobante_hash text -- Solo hash: prueba privada para recuperar una compra invitada.
);
create table public.detalle_pedido (
 id_detalle_pedido bigint generated by default as identity primary key,
 id_pedido uuid not null references public.pedido,
 id_producto bigint not null references public.producto,
 titulo_compra varchar(150) not null, edicion_compra varchar(80) not null,
 plataforma_compra varchar(30) not null, region_compra varchar(40) not null,
 precio_unitario_centavos integer not null check(precio_unitario_centavos>=0),
 precio_anterior_centavos integer check(precio_anterior_centavos>precio_unitario_centavos),
 unique(id_pedido,id_producto), unique(id_detalle_pedido,id_producto)
);
create table public.clave_digital (
 id_clave bigint generated by default as identity primary key,
 id_producto bigint not null references public.producto,
 codigo varchar(120) not null unique check(codigo like 'DEMO-%'),
 estado varchar(15) not null default 'DISPONIBLE' check(estado in ('DISPONIBLE','ENTREGADA')),
 id_detalle_pedido bigint unique,
 ingresada_en timestamptz not null default now(), entregada_en timestamptz,
 foreign key(id_detalle_pedido,id_producto) references public.detalle_pedido(id_detalle_pedido,id_producto),
 check((estado='DISPONIBLE' and id_detalle_pedido is null and entregada_en is null) or
       (estado='ENTREGADA' and id_detalle_pedido is not null and entregada_en is not null))
);
create table public.metodo_pago (
 id_metodo_pago smallint generated by default as identity primary key,
 codigo varchar(20) not null unique check(codigo in ('tarjeta','paypal')),
 nombre varchar(40) not null, activo boolean not null default true
);
create table public.pago (
 id_pago uuid primary key default gen_random_uuid(), id_pedido uuid not null references public.pedido,
 id_metodo_pago smallint not null references public.metodo_pago,
 importe_centavos integer not null check(importe_centavos>=0),
 estado varchar(15) not null check(estado in ('PENDIENTE','APROBADO','RECHAZADO')),
 referencia varchar(100) not null unique, creado_en timestamptz not null default now(), confirmado_en timestamptz,
 check((estado='PENDIENTE')=(confirmado_en is null))
);
create unique index un_pago_aprobado on public.pago(id_pedido) where estado='APROBADO';
create index on public.usuario(id_rol);
create index on public.producto(id_categoria);
create index on public.clave_digital(id_producto,estado);
