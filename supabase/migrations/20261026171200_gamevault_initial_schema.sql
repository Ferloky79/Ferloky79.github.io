-- Estas funciones privilegiadas viven en un esquema NO expuesto por la Data API.
-- Cada operación privada valida al propietario; el catálogo revela únicamente datos comerciales.
create function private.es_admin() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.usuario u join public.rol r using(id_rol)
 where u.id_usuario=(select auth.uid()) and u.activo and r.nombre='ADMIN');
$$;
create function private.es_cliente_activo() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.usuario where id_usuario=(select auth.uid()) and activo);
$$;
create function private.crear_perfil() returns trigger language plpgsql security definer set search_path='' as $$
 begin
 insert into public.usuario(id_usuario,id_rol,nombre) values(new.id,2,
 left(coalesce(nullif(trim(new.raw_user_meta_data->>'nombre'),''),'Jugador'),100));
 return new;
 end;
$$;
create trigger alta_perfil after insert on auth.users for each row execute function private.crear_perfil();

